import AppKit

public enum PasteboardIO {
    // Provenance/automation markers can be ready before the promised text bytes.
    // Preserve them alongside real payloads, but never treat them as clipboard content.
    /// Call from one serial capture queue. No AppKit views or image decoding here.
    public static func read(_ pasteboard: NSPasteboard, source: String, captureTemporaryText: Bool = false) throws -> ClipboardSnapshot? {
        let before = pasteboard.changeCount
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        let types = items.flatMap { $0.types.map(\.rawValue) }
        guard !CapturePolicy.shouldIgnore(types: types, captureTemporaryText: captureTemporaryText) else { return nil }
        var bytes = 0
        var captured: [ClipboardItem] = []
        for item in items {
            var representations: [Representation] = []
            for type in item.types {
                // Promised drag providers and ownership markers are not durable clipboard data.
                if type.rawValue == "com.apple.pasteboard.promised-file-url" { continue }
                // Apps often declare lazy types they never fulfil; keep everything that is real.
                guard let data = item.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= CapturePolicy.maxPasteboardBytes else { throw HistoryError.tooLarge }
                representations.append(.init(type: type.rawValue, data: data))
            }
            if !representations.isEmpty { captured.append(ClipboardItem(representations)) }
        }
        let hasPayload = captured.contains { item in
            item.representations.contains { !CapturePolicy.metadataTypes.contains($0.type) && !$0.data.isEmpty }
        }
        guard before == pasteboard.changeCount, hasPayload else { return nil }
        return ClipboardSnapshot(items: captured, source: source)
    }
    @discardableResult public static func write(_ items: [ClipboardItem], to pasteboard: NSPasteboard, markGenerated: Bool = true) -> Bool {
        guard !items.isEmpty else { return false }
        let objects = items.map { item -> NSPasteboardItem in
            let result = NSPasteboardItem()
            for rep in item.representations { result.setData(rep.data, forType: .init(rep.type)) }
            if markGenerated {
                result.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
                result.setData(Data(), forType: .init(CapturePolicy.replayType))
            }
            return result
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects(objects)
    }
}
