import Foundation
import CryptoKit

public struct Representation: Codable, Sendable, Equatable {
    public var type: String
    public var data: Data
    public init(type: String, data: Data) { self.type = type; self.data = data }
}

public struct ClipboardItem: Codable, Sendable, Equatable {
    public var representations: [Representation]
    public init(_ representations: [Representation]) { self.representations = representations }
    public func data(for type: String) -> Data? { representations.first { $0.type == type }?.data }
    public var fileURL: URL? {
        guard let data = data(for: "public.file-url"), let string = String(data: data, encoding: .utf8),
              let url = URL(string: string), url.isFileURL else { return nil }
        return url
    }
}

public struct ClipboardSnapshot: Sendable {
    public var items: [ClipboardItem]
    public var source: String
    public var capturedAt: Date
    public init(items: [ClipboardItem], source: String = "", capturedAt: Date = Date()) {
        self.items = items; self.source = source; self.capturedAt = capturedAt
    }
    public var byteCount: Int { items.reduce(0) { $0 + $1.representations.reduce(0) { $0 + $1.data.count } } }
    public var fingerprint: String {
        var hash = SHA256()
        func append(_ data: Data) {
            var size = UInt64(data.count).littleEndian
            withUnsafeBytes(of: &size) { hash.update(data: Data($0)) }
            hash.update(data: data)
        }
        for item in items {
            append(Data("item".utf8))
            for rep in item.representations.sorted(by: { $0.type < $1.type }) {
                append(Data(rep.type.utf8)); append(rep.data)
            }
            if let url = item.fileURL,
               let values = try? url.resourceValues(forKeys: [.contentModificationDateKey, .fileSizeKey]) {
                append(Data("\(values.contentModificationDate?.timeIntervalSince1970 ?? 0):\(values.fileSize ?? 0)".utf8))
            }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

public enum ClipKind: String, Codable, Sendable { case text, image, audio, file, other }

public struct HistoryEntry: Identifiable, Sendable, Equatable {
    public let id: String
    public let title: String
    public let text: String
    public let kind: ClipKind
    public let source: String
    public let created: Date
    public let lastUsed: Date
    public let byteCount: Int64
    public let thumbnailPath: String?
    public init(id: String, title: String, text: String, kind: ClipKind, source: String,
                created: Date, lastUsed: Date, byteCount: Int64, thumbnailPath: String?) {
        self.id = id; self.title = title; self.text = text; self.kind = kind; self.source = source
        self.created = created; self.lastUsed = lastUsed; self.byteCount = byteCount
        self.thumbnailPath = thumbnailPath
    }
}

public enum HistoryError: LocalizedError {
    case database(String), invalidPayload, tooLarge, inaccessibleFile(String), unsupportedVersion
    public var errorDescription: String? {
        switch self {
        case .database(let reason): return "History database: \(reason)"
        case .invalidPayload: return "This clipboard item could not be read completely."
        case .tooLarge: return "This copy exceeds the capture limit and was not saved."
        case .inaccessibleFile(let name): return "Could not archive \(name). The copy was not saved."
        case .unsupportedVersion: return "This history was created by a newer version of SuperCopy."
        }
    }
}

public enum CapturePolicy {
    public static let maxPasteboardBytes = 128 * 1024 * 1024
    public static let maxFileBytes: Int64 = 1024 * 1024 * 1024
    public static let replayType = "app.supercopy.replayed"
    public static let transientType = "org.nspasteboard.TransientType"
    private static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]
    public static let sensitiveTypes = concealedTypes.union([transientType])
    static let metadataTypes: Set<String> = [
        "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.source", replayType, transientType,
        "org.chromium.internal.source-rfh-token", "org.chromium.source-url"
    ]
    private static let textTypes: Set<String> = [
        "public.utf8-plain-text", "public.utf16-external-plain-text", "public.utf16-plain-text",
        "public.rtf", "public.html", "NSStringPboardType", "NSRTFPboardType", "Apple HTML pasteboard type"
    ]
    private static let temporaryTextTypes = textTypes.union(metadataTypes).union([transientType])

    public static func shouldHidePreview(types: [String], captureTemporaryText: Bool = false) -> Bool {
        guard concealedTypes.isDisjoint(with: types) else { return true }
        guard types.contains(transientType) else { return false }
        // Explicit opt-in is limited to known text/provenance formats. Temporary files,
        // images, arbitrary data and password/concealed markers are never admitted.
        return !captureTemporaryText || textTypes.isDisjoint(with: types) || !Set(types).isSubset(of: temporaryTextTypes)
    }
    public static func shouldIgnore(types: [String], captureTemporaryText: Bool = false) -> Bool {
        types.contains(replayType) || shouldHidePreview(types: types, captureTemporaryText: captureTemporaryText)
    }
}
